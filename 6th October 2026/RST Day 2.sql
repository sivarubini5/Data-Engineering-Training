"Find claims that are above the overall average claim amount."

First calculate the average:

SELECT AVG(claim_amount)
FROM insurance_claims;

You could put that into a CTE:

WITH average_claim AS (
    SELECT AVG(claim_amount) AS avg_amount
    FROM insurance_claims
)
SELECT *
FROM insurance_claims
WHERE claim_amount > (
    SELECT avg_amount
    FROM average_claim
