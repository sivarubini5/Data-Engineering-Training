/*
Simple rule

ROW_NUMBER

Everyone gets a different number.

RANK

Same values get the same rank, and gaps are created.

DENSE_RANK

Same values get the same rank, but no gaps.
Why are these called Window Functions?
it creates the window over which SQL performs the calculation

FUNCTION() OVER(...)

ask three questions.

Question 1 — What am I calculating?
RANK()
ROW_NUMBER()
DENSE_RANK()
SUM()
AVG()
LAG()
LEAD()
Question 2 — Should I divide into groups?

If yes:

PARTITION BY team

If no, leave it out.

Question 3 — In what order?
ORDER BY calls_handled DESC

For ranking:

PARTITION BY → Who should compete together?

ORDER BY → What determines their position?

Exercises

