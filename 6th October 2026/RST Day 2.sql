/*
CTE (WITH) → create a temporary named result and use it in the main query.
Correlated subquery → a subquery that depends on the current row of the outer query.
1. CTE — Common Table Expression

A CTE is basically a temporary result set with a name.
Instead of writing one huge query like:

Calculate totals → filter them → rank them → display them

you can break the work into steps:

Step 1 → CTE
Step 2 → Main query

The basic syntax is:

WITH cte_name AS (
    SELECT ...
)
SELECT ...
FROM cte_name;
The biggest advantage is readability.
CTE is NOT a permanent table
For example:

WITH claim_totals AS (
